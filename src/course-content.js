const VERIFIED_RANGE = "教材小节及页码范围已核验";

const knowledge = (id, title, importance, keywords, keyPoints, extra = {}) => ({
  id,
  title,
  importance,
  keywords,
  keyPoints,
  ...extra
});

const section = (id, title, page, points) => ({ id, title, page, points });

const chapter = (id, number, title, summary, importance, memoryOutline, sections) => ({
  id,
  number,
  title,
  summary,
  importance,
  memoryOutline,
  sections
});

function withTextbookSources(course) {
  return {
    ...course,
    chapters: course.chapters.map((chapterItem) => {
      const points = chapterItem.sections.flatMap((sectionItem) => sectionItem.points);
      return {
        ...chapterItem,
        sections: chapterItem.sections.map((sectionItem) => ({
          ...sectionItem,
          points: sectionItem.points.map((item) => ({
            ...item,
            source: {
              book: course.book,
              edition: course.edition,
              chapter: chapterItem.title,
              section: sectionItem.title,
              page: sectionItem.page,
              verification: VERIFIED_RANGE
            }
          }))
        })),
        examPractice: {
          prompt: `结合材料，说明${chapterItem.title}中相关问题的基本内容、内在关系和现实或历史意义。`,
          answer: points.slice(0, 4).map((item) => item.keyPoints[0]),
          scoring: points.slice(0, 4).map((item) => `准确说明“${item.title}”所对应的核心内容。`)
        }
      };
    })
  };
}

