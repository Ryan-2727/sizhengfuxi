$$;

drop trigger if exists questions_initialize_quality on public.questions;
create trigger questions_initialize_quality
after insert on public.questions
for each row execute function public.initialize_question_quality();

create or replace function public.prevent_question_payload_update()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.payload is distinct from old.payload then
    raise exception 'questions.payload is immutable; create a question revision instead';
  end if;
  return new;
end;
$$;

drop trigger if exists questions_prevent_payload_update on public.questions;
create trigger questions_prevent_payload_update
before update of payload on public.questions
for each row execute function public.prevent_question_payload_update();

create or replace function public.validate_question_quality_links()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  revision_question_id uuid;
begin
  if new.current_revision_id is not null then
    select question_id into revision_question_id
    from public.question_revisions
    where id = new.current_revision_id;
    if revision_question_id is null or revision_question_id <> new.question_id then
      raise exception 'current revision must belong to the same question';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists question_quality_validate_links on public.question_quality;
create trigger question_quality_validate_links
before insert or update of current_revision_id on public.question_quality
for each row execute function public.validate_question_quality_links();

drop trigger if exists question_quality_set_updated_at on public.question_quality;
create trigger question_quality_set_updated_at
before update on public.question_quality
for each row execute function public.set_updated_at();

create or replace function public.log_question_quality_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.question_quality_events (question_id, event_type, before_state, after_state)
  values (new.question_id, 'quality-update', to_jsonb(old), to_jsonb(new));
  return new;
end;
$$;

drop trigger if exists question_quality_log_change on public.question_quality;
create trigger question_quality_log_change
after update on public.question_quality
for each row execute function public.log_question_quality_change();

create or replace function public.is_question_published(target_question_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.question_quality
    where question_id = target_question_id
      and publication_status = 'published'
  );
$$;

create or replace function public.is_current_published_revision(target_revision_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.question_quality
    where current_revision_id = target_revision_id
      and publication_status = 'published'
  );
$$;

revoke all on function public.is_question_published(uuid) from public;
revoke all on function public.is_current_published_revision(uuid) from public;
grant execute on function public.is_question_published(uuid) to authenticated;
grant execute on function public.is_current_published_revision(uuid) to authenticated;

