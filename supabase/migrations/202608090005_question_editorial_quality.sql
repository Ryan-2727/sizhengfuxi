create extension if not exists pgcrypto;

create table if not exists public.question_revisions (
  id uuid primary key default gen_random_uuid(),
  question_id uuid not null references public.questions(id) on delete cascade,
  revision_no integer not null check (revision_no > 0),
  display_question text,
  display_answer text,
  display_analysis text,
  correct_answer_override text check (correct_answer_override is null or correct_answer_override ~ '^[A-F]+$'),
  question_type_override text check (question_type_override is null or question_type_override in ('单选题', '多选题', '大题')),
  scoring_points jsonb not null default '[]'::jsonb check (jsonb_typeof(scoring_points) = 'array'),
  keywords jsonb not null default '[]'::jsonb check (jsonb_typeof(keywords) = 'array'),
  common_mistakes jsonb not null default '[]'::jsonb check (jsonb_typeof(common_mistakes) = 'array'),
  revision_note text not null,
  verification_reference text,
  created_at timestamptz not null default now(),
  unique (question_id, revision_no)
);

create table if not exists public.question_quality (
  question_id uuid primary key references public.questions(id) on delete cascade,
  publication_status text not null default 'published'
    check (publication_status in ('published', 'hidden_duplicate', 'hidden_error', 'hidden_review')),
  review_status text not null default 'unreviewed'
    check (review_status in ('unreviewed', 'structural_checked', 'source_verified', 'needs_manual_review')),
  canonical_question_id uuid references public.questions(id) on delete restrict,
  chapter_confidence numeric check (chapter_confidence is null or (chapter_confidence >= 0 and chapter_confidence <= 1)),
  verification_status text not null default 'pending'
    check (verification_status in ('teacher-key-verified', 'textbook-law-verified', 'authoritative-source-verified', 'source-backed', 'pending')),
  source_kind text,
  source_title text,
  source_edition text,
  source_chapter text,
  source_page text,
  source_url text,
  verification_reference text,
  current_revision_id uuid references public.question_revisions(id) on delete set null,
  original_payload_hash text not null check (original_payload_hash ~ '^[a-f0-9]{64}$'),
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (canonical_question_id is null or canonical_question_id <> question_id),
  check (publication_status <> 'hidden_duplicate' or canonical_question_id is not null)
);

create table if not exists public.question_quality_events (
  id bigint generated by default as identity primary key,
  question_id uuid not null references public.questions(id) on delete cascade,
  event_type text not null,
  before_state jsonb,
  after_state jsonb,
  actor text not null default current_user,
  created_at timestamptz not null default now()
);

create index if not exists question_quality_publication_idx
  on public.question_quality (publication_status, review_status);
create index if not exists question_quality_canonical_idx
  on public.question_quality (canonical_question_id)
  where canonical_question_id is not null;
create index if not exists question_revisions_question_idx
  on public.question_revisions (question_id, revision_no desc);
create index if not exists question_quality_events_question_idx
  on public.question_quality_events (question_id, created_at desc);

insert into public.question_quality (
  question_id,
  publication_status,
  review_status,
  verification_status,
  source_kind,
  source_title,
  verification_reference,
  original_payload_hash,
  verified_at
)
select
  q.id,
  'published',
  case
    when q.payload ->> 'auditStatus' in ('teacher-key-verified', 'textbook-law-verified', 'authoritative-source-verified')
      and nullif(trim(q.payload ->> 'verificationReference'), '') is not null then 'source_verified'
    when q.payload ->> 'auditStatus' = 'source-backed' then 'structural_checked'
    else 'needs_manual_review'
  end,
  case
    when q.payload ->> 'auditStatus' in ('teacher-key-verified', 'textbook-law-verified', 'authoritative-source-verified', 'source-backed')
      then q.payload ->> 'auditStatus'
    else 'pending'
  end,
  case
    when coalesce(q.payload ->> 'source', '') ~ '教师|老师|课堂' then 'teacher-material'
    when coalesce(q.payload ->> 'source', '') ~ '真题|考试大纲|自学考试' then 'public-exam'
    when coalesce(q.payload ->> 'source', '') ~ '教材|课程|整理' then 'textbook-review'
    else 'question-bank'
  end,
  nullif(trim(q.payload ->> 'source'), ''),
  nullif(trim(q.payload ->> 'verificationReference'), ''),
  encode(digest(q.payload::text, 'sha256'), 'hex'),
  case
    when q.payload ->> 'auditStatus' in ('teacher-key-verified', 'textbook-law-verified', 'authoritative-source-verified')
      and nullif(trim(q.payload ->> 'verificationReference'), '') is not null then now()
    else null
  end
from public.questions q
on conflict (question_id) do nothing;

